-- ---------------------------------------------------------------------------
-- HU01 - Cadastro de Usuarios
--
-- Escrito em SQL padrao e de forma idempotente (IF NOT EXISTS), para que o
-- MESMO arquivo possa ser executado no PostgreSQL do Supabase e no H2 em
-- modo de compatibilidade PostgreSQL usado pelos testes.
--
-- O Hibernate roda com ddl-auto: validate. Ele NUNCA cria nem altera tabela:
-- apenas falha de inmediato se o schema divergir da entidade. A criacao
-- da estrutura e sempre feita por este arquivo.
--
-- Escopo: apenas o que as HUs 01 e 03 exigem - nome, e-mail, senha, meta
-- de estudo semanal e objetivo. Nenhuma tabela de planner, edital,
-- disciplina, desempenho, questao ou flashcard.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS usuario (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(180) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,

    -- Impede o cadastro de um e-mail ja existente, tambem no nivel do banco
    CONSTRAINT uk_usuario_email UNIQUE (email)
);

-- ---------------------------------------------------------------------------
-- HU03 - Gerenciamento de Perfis
--
-- Campos opcionais do perfil. ADD COLUMN IF NOT EXISTS e idempotente tanto no
-- PostgreSQL (9.6+) quanto no H2 em modo PostgreSQL usado pelos testes: a
-- tabela ja existe no Supabase desde a HU01, entao a migracao das contas
-- existentes e apenas o ALTER, sem recriar nada.
-- ---------------------------------------------------------------------------

ALTER TABLE usuario ADD COLUMN IF NOT EXISTS meta_estudo_semanal INTEGER;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS objetivo_motivacao VARCHAR(500);

-- ---------------------------------------------------------------------------
-- HU04 - Perfis de Acesso Diferenciados
--
-- Perfil da conta: ADMIN ou ALUNO. O banco e a fonte de verdade (criterio 1
-- da HU): o cadastro grava sempre o default 'ALUNO', e a promocao a ADMIN e
-- uma operacao manual no banco, documentada na HU. O JWT carrega uma copia do
-- perfil para o backend autorizar sem consultar o banco a cada requisicao -
-- por isso uma promocao so reflete apos novo login.
--
-- A lista de valores e validada na aplicacao: um CHECK constraint usaria
-- ADD CONSTRAINT, que nao e idempotente no PostgreSQL (quebraria o segundo
-- boot deste arquivo). Constraints entram na estruturacao do banco da HU05.
-- ---------------------------------------------------------------------------

ALTER TABLE usuario ADD COLUMN IF NOT EXISTS perfil VARCHAR(20) NOT NULL DEFAULT 'ALUNO';