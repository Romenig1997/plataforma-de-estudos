CREATE TABLE questao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 edital_id BIGINT NOT NULL REFERENCES edital(id),
 conteudo_id BIGINT NOT NULL REFERENCES conteudo(id),
 enunciado TEXT NOT NULL,
 gabarito INTEGER NOT NULL CHECK (gabarito BETWEEN 0 AND 3),
 explicacao TEXT NOT NULL,
 publicada BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE questao_alternativa (
 questao_id BIGINT NOT NULL REFERENCES questao(id),
 ordem INTEGER NOT NULL CHECK (ordem BETWEEN 0 AND 3),
 texto TEXT NOT NULL,
 PRIMARY KEY(questao_id,ordem)
);
CREATE TABLE resposta_questao (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 questao_id BIGINT NOT NULL REFERENCES questao(id),
 alternativa INTEGER NOT NULL CHECK (alternativa BETWEEN 0 AND 3),
 correta BOOLEAN NOT NULL,
 respondida_em TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(usuario_id,questao_id)
);
