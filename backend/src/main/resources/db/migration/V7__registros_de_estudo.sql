CREATE TABLE registro_estudo (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id),
 conteudo_id BIGINT NOT NULL REFERENCES conteudo(id),
 concluido BOOLEAN NOT NULL DEFAULT FALSE,
 questoes INTEGER NOT NULL DEFAULT 0 CHECK (questoes BETWEEN 0 AND 1000000),
 acertos INTEGER NOT NULL DEFAULT 0 CHECK (acertos >= 0 AND acertos <= questoes),
 atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
 UNIQUE(usuario_id,conteudo_id)
);
