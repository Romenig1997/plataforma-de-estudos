CREATE TABLE plano_estudo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario(id),
    edital_id BIGINT NOT NULL REFERENCES edital(id),
    meta_horas_semanais INTEGER NOT NULL CHECK (meta_horas_semanais BETWEEN 1 AND 168),
    atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE plano_disciplina (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plano_id BIGINT NOT NULL REFERENCES plano_estudo(id),
    disciplina_id BIGINT NOT NULL REFERENCES disciplina(id),
    prioridade VARCHAR(10) NOT NULL CHECK (prioridade IN ('BAIXA', 'NORMAL', 'ALTA')),
    minutos_semanais INTEGER NOT NULL CHECK (minutos_semanais >= 0),
    CONSTRAINT uk_plano_disciplina UNIQUE (plano_id, disciplina_id)
);
