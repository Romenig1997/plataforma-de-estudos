-- ---------------------------------------------------------------------------
-- V3 - HU07 (incremento A): edital e importacao de editais em PDF
--
-- Move o "edital" que a HU07 menciona (criterio 3: disciplinas e conteudos do
-- edital selecionado) para o banco: a importacao (PDF + extracao + revisao) e
-- separada do edital aprovado, que e o que o planner consome.
--
-- cria em ordem de dependencia (FKs):
--   edital_pdf   -> PDF original (bytea) + sha256 de deduplicacao
--   edital       -> edital aprovado (titulo, orgao, ano) + referencia ao PDF
--   importacao_edital -> ciclo upload -> extracao -> revisao -> aprovacao;
--                        guarda o JSON extraido (conteudo_extraido) e os erros
--                        da validacao (erros_validacao), ambos TEXT
--   concurso/cargo, disciplina/conteudo -> arvore estruturada aprovada;
--                        conteudo e unitario: assunto (pai_id NULO) e
--                        subassunto (pai_id -> assunto), com pagina de origem
-- ---------------------------------------------------------------------------

CREATE TABLE edital_pdf (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_original VARCHAR(255) NOT NULL,
    tamanho_bytes BIGINT NOT NULL,
    tipo          VARCHAR(50) NOT NULL,
    sha256        VARCHAR(64) NOT NULL,
    bytes         BYTEA NOT NULL,
    criado_em     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_edital_pdf_sha256 UNIQUE (sha256)
);

CREATE TABLE edital (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo        VARCHAR(255) NOT NULL,
    orgao         VARCHAR(120) NOT NULL,
    ano           INTEGER NOT NULL,
    edital_pdf_id BIGINT,
    criado_em     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_edital_titulo_orgao_ano UNIQUE (titulo, orgao, ano),
    CONSTRAINT fk_edital_pdf FOREIGN KEY (edital_pdf_id) REFERENCES edital_pdf (id)
);

CREATE TABLE importacao_edital (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edital_pdf_id            BIGINT NOT NULL,
    status                   VARCHAR(30) NOT NULL,
    total_paginas            INTEGER NOT NULL,
    conteudo_extraido        TEXT NOT NULL,
    erros_validacao          TEXT,
    edital_aprovado_id       BIGINT,
    importado_por_usuario_id BIGINT NOT NULL,
    criado_em                TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em            TIMESTAMP,

    CONSTRAINT fk_importacao_edital_pdf  FOREIGN KEY (edital_pdf_id) REFERENCES edital_pdf (id),
    CONSTRAINT fk_importacao_edital      FOREIGN KEY (edital_aprovado_id) REFERENCES edital (id),
    CONSTRAINT fk_importacao_usuario     FOREIGN KEY (importado_por_usuario_id) REFERENCES usuario (id)
);

CREATE TABLE concurso (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edital_id BIGINT NOT NULL,
    nome      VARCHAR(255) NOT NULL,

    CONSTRAINT uk_concurso_edital_nome UNIQUE (edital_id, nome),
    CONSTRAINT fk_concurso_edital FOREIGN KEY (edital_id) REFERENCES edital (id)
);

CREATE TABLE cargo (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    concurso_id BIGINT NOT NULL,
    nome        VARCHAR(255) NOT NULL,

    CONSTRAINT uk_cargo_concurso_nome UNIQUE (concurso_id, nome),
    CONSTRAINT fk_cargo_concurso FOREIGN KEY (concurso_id) REFERENCES concurso (id)
);

CREATE TABLE disciplina (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    edital_id BIGINT NOT NULL,
    nome      VARCHAR(255) NOT NULL,
    pagina    INTEGER NOT NULL,

    CONSTRAINT uk_disciplina_edital_nome UNIQUE (edital_id, nome),
    CONSTRAINT fk_disciplina_edital FOREIGN KEY (edital_id) REFERENCES edital (id)
);

CREATE TABLE conteudo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id BIGINT NOT NULL,
    pai_id        BIGINT,
    nome          VARCHAR(255) NOT NULL,
    pagina        INTEGER NOT NULL,

    CONSTRAINT fk_conteudo_disciplina FOREIGN KEY (disciplina_id) REFERENCES disciplina (id),
    CONSTRAINT fk_conteudo_pai        FOREIGN KEY (pai_id) REFERENCES conteudo (id)
);