-- V2 - HU05: perfis de acesso com tabela propria e relacionamento
--
-- Atende aos criterios de aceite da HU05:
--   1. tabela de usuario e tabela de perfis criada  (a `perfil` nasce aqui);
--   2. relacionamento entre as tabelas definido      (FK usuario.perfil_id);
--   3. senhas armazenadas de forma nao reversivel     (mantido o hash PBKDF2
--      da HU01, coluna senha_hash - nada a fazer aqui).
--
-- Antes da HU05 o perfil era a coluna de texto `usuario.perfil` (HU04). Agora
-- existe a tabela `perfil` (catalogo ADMIN/ALUNO) e `usuario.perfil_id` aponta
-- para ela: relacao 1:N (um perfil tem muitos usuarios). A migracao preserva
-- as contas existentes - o backfill converte o texto antigo em FK, e so depois
-- a coluna antiga e removida.
-- ---------------------------------------------------------------------------

CREATE TABLE perfil (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(20) NOT NULL,
    descricao VARCHAR(120),

    CONSTRAINT uk_perfil_nome UNIQUE (nome)
);

INSERT INTO perfil (nome, descricao) VALUES ('ALUNO', 'Aluno');
INSERT INTO perfil (nome, descricao) VALUES ('ADMIN', 'Administrador');

-- Liga cada usuario ao perfil correspondente. Correlaciona pelo nome gravado
-- na coluna antiga, que so podia ser 'ALUNO' ou 'ADMIN'.
ALTER TABLE usuario ADD COLUMN perfil_id BIGINT;

UPDATE usuario u
   SET perfil_id = (SELECT p.id FROM perfil p WHERE p.nome = u.perfil);

ALTER TABLE usuario ALTER COLUMN perfil_id SET NOT NULL;

ALTER TABLE usuario
    ADD CONSTRAINT fk_usuario_perfil FOREIGN KEY (perfil_id) REFERENCES perfil (id);

ALTER TABLE usuario DROP COLUMN perfil;
