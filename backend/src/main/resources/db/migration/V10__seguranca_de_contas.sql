-- V10 - seguranca de contas: confirmacao de e-mail, redefinicao de senha e
-- versao de sessao para invalidar tokens emitidos antes de uma troca de senha.

ALTER TABLE usuario ADD COLUMN email_verificado BOOLEAN NOT NULL DEFAULT FALSE;
-- Contas existentes foram criadas antes da confirmacao e ja sao consideradas
-- verificadas; somente novos cadastros precisam confirmar o endereco.
UPDATE usuario SET email_verificado = TRUE;

ALTER TABLE usuario ADD COLUMN sessao_versao INTEGER NOT NULL DEFAULT 0;

CREATE TABLE token_conta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE CASCADE,
    tipo VARCHAR(32) NOT NULL,
    hash_token VARCHAR(64) NOT NULL,
    expira_em TIMESTAMP WITH TIME ZONE NOT NULL,
    usado_em TIMESTAMP WITH TIME ZONE,
    criado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_token_conta_hash UNIQUE(hash_token)
);

CREATE INDEX ix_token_conta_usuario_tipo ON token_conta(usuario_id, tipo);
