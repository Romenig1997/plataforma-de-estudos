CREATE TABLE cronograma_estudo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuario(id),
    plano_id BIGINT NOT NULL REFERENCES plano_estudo(id),
    edital_id BIGINT NOT NULL REFERENCES edital(id),
    semana_inicio DATE NOT NULL,
    meta_horas_semanais INTEGER NOT NULL CHECK (meta_horas_semanais BETWEEN 1 AND 168),
    plano_atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    gerado_em TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE disponibilidade_estudo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cronograma_id BIGINT NOT NULL REFERENCES cronograma_estudo(id),
    dia_semana INTEGER NOT NULL CHECK (dia_semana BETWEEN 1 AND 7),
    inicio TIME NOT NULL,
    fim TIME NOT NULL,
    CHECK (inicio < fim)
);
CREATE TABLE atividade_estudo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cronograma_id BIGINT NOT NULL REFERENCES cronograma_estudo(id),
    disciplina_id BIGINT NOT NULL REFERENCES disciplina(id),
    conteudo_id BIGINT NOT NULL REFERENCES conteudo(id),
    data DATE NOT NULL,
    inicio TIME NOT NULL,
    fim TIME NOT NULL,
    CHECK (inicio < fim)
);
