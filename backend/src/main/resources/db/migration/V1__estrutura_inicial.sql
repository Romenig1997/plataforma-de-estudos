-- ---------------------------------------------------------------------------
-- V1 - Estrutura inicial (baseline)
--
-- Representa o esquema que ja existia antes da HU05: a tabela `usuario` com as
-- colunas das HUs 01 (nome, e-mail, senha), 03 (meta de estudo semanal,
-- objetivo) e 04 (perfil como texto).
--
-- O banco do Supabase ja tem essa estrutura, criada pelo antigo schema.sql
-- idempotente. Por isso a aplicacao sobe com baseline-on-migrate e
-- baseline-version=1: nesse banco o Flyway apenas registra a versao 1 como
-- baseline e NAO executa este arquivo, aplicando so a V2 em diante. Num banco
-- vazio (o H2 dos testes), o Flyway executa a V1 e a V2 do zero.
--
-- Este arquivo e imutavel: uma vez aplicado, nao se edita - a evolucao entra
-- em uma migration nova.
-- ---------------------------------------------------------------------------

CREATE TABLE usuario (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                VARCHAR(120) NOT NULL,
    email               VARCHAR(180) NOT NULL,
    senha_hash          VARCHAR(255) NOT NULL,
    meta_estudo_semanal INTEGER,
    objetivo_motivacao  VARCHAR(500),
    perfil              VARCHAR(20) NOT NULL DEFAULT 'ALUNO',

    CONSTRAINT uk_usuario_email UNIQUE (email)
);
