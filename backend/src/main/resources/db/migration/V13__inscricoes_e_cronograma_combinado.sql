-- ---------------------------------------------------------------------------
-- Varios cursos por aluno (continuacao da V12).
--
-- 1. Cada plano passa a ser a inscricao do aluno em um edital: no maximo um
--    plano por (usuario, edital). Um deles fica "em foco" e e o curso que as
--    telas abrem por padrao. Os planos existentes viram o foco do seu aluno.
-- 2. O cronograma continua unico por aluno, mas combina todos os cursos. A
--    tabela cronograma_plano guarda quais planos (e em que versao) geraram a
--    agenda, para indicar quando ela ficou desatualizada.
-- 3. As colunas plano_id/edital_id/plano_atualizado_em de cronograma_estudo
--    deixam de ser usadas: os dados vao para cronograma_plano e elas ficam
--    nulas, para nao prender a exclusao de um plano.
-- ---------------------------------------------------------------------------

ALTER TABLE plano_estudo ADD COLUMN em_foco BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE plano_estudo SET em_foco = TRUE;
ALTER TABLE plano_estudo ADD CONSTRAINT uk_plano_usuario_edital UNIQUE (usuario_id, edital_id);

CREATE TABLE cronograma_plano (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cronograma_id BIGINT NOT NULL REFERENCES cronograma_estudo(id),
    plano_id BIGINT NOT NULL REFERENCES plano_estudo(id),
    plano_atualizado_em TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_cronograma_plano UNIQUE (cronograma_id, plano_id)
);

INSERT INTO cronograma_plano (cronograma_id, plano_id, plano_atualizado_em)
SELECT id, plano_id, plano_atualizado_em FROM cronograma_estudo;

ALTER TABLE cronograma_estudo ALTER COLUMN plano_id DROP NOT NULL;
ALTER TABLE cronograma_estudo ALTER COLUMN edital_id DROP NOT NULL;
ALTER TABLE cronograma_estudo ALTER COLUMN plano_atualizado_em DROP NOT NULL;
UPDATE cronograma_estudo SET plano_id = NULL, edital_id = NULL, plano_atualizado_em = NULL;
